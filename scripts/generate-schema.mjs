import { readFile, writeFile } from "node:fs/promises";
import * as z from "zod";
import { buildIdentitySchema } from "../dist/spec/build-identity.js";
import { standaloneCheckSchema } from "../dist/spec/check.js";

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  throw new Error("Usage: node scripts/generate-schema.mjs [--check]");
}

const schemas = [
  { name: "build", source: "build-identity", schema: buildIdentitySchema },
  { name: "check", source: "check", schema: standaloneCheckSchema },
];

for (const { name, source, schema } of schemas) {
  const path = new URL(`../src/spec/${name}.schema.json`, import.meta.url);
  const generated = {
    $comment: `Generated by npm run generate:schema from src/spec/${source}.ts. Do not edit manually.`,
    ...z.toJSONSchema(schema, { target: "draft-2020-12", io: "input" }),
  };
  const contents = `${JSON.stringify(generated, null, 2)}\n`;

  if (args[0] === "--check") {
    const current = await readFile(path, "utf8").catch((error) => {
      if (error.code === "ENOENT") return undefined;
      throw error;
    });
    if (current !== contents) {
      throw new Error(`Generated ${name} schema is missing or out of date. Run npm run generate:schema.`);
    }
    console.log(`Generated ${name} schema is current.`);
  } else {
    await writeFile(path, contents);
    console.log(`Generated src/spec/${name}.schema.json.`);
  }
}
