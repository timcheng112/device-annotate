import { readFile, writeFile } from "node:fs/promises";
import * as z from "zod";
import { buildIdentitySchema } from "../dist/spec/build-identity.js";
import { standaloneCheckSchema } from "../dist/spec/check.js";
import { annotationSchema } from "../dist/spec/annotation.js";
import { cropSchema } from "../dist/spec/crop.js";
import { defaultsSchema, stepSchema } from "../dist/spec/step.js";
import { specStructureSchema } from "../dist/spec/schema.js";
import { retentionSchema } from "../dist/spec/retention.js";
import { recordingOptionsSchema } from "../dist/spec/recordings.js";
import { preCaptureErrorSchema } from "../dist/spec/errors.js";
import { outputOwnerSchema } from "../dist/manifest/owner.js";
import { completedCheckSchema, entryErrorSchema } from "../dist/manifest/evaluation.js";
import { environmentStructureSchema } from "../dist/manifest/environment.js";
import { attemptArtifactsStructureSchema } from "../dist/manifest/artifacts.js";
import { attemptStructureSchema } from "../dist/manifest/attempt.js";
import { manifestStructureSchema } from "../dist/manifest/schema.js";
import { geometryStructureSchema } from "../dist/manifest/geometry.js";

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  throw new Error("Usage: node scripts/generate-schema.mjs [--check]");
}

const schemas = [
  { name: "build", source: "build-identity", schema: buildIdentitySchema },
  { name: "check", source: "check", schema: standaloneCheckSchema },
  { name: "annotation", source: "annotation", schema: annotationSchema },
  { name: "crop", source: "crop", schema: cropSchema },
  { name: "defaults", source: "step", schema: defaultsSchema },
  { name: "step", source: "step", schema: stepSchema },
  { name: "spec", source: "schema", schema: specStructureSchema },
  { name: "retention", source: "retention", schema: retentionSchema },
  { name: "recordings", source: "recordings", schema: recordingOptionsSchema },
  { name: "pre-capture-error", source: "errors", schema: preCaptureErrorSchema },
  { name: "owner", source: "owner", directory: "manifest", schema: outputOwnerSchema },
  { name: "completed-check", source: "evaluation", directory: "manifest", schema: completedCheckSchema },
  { name: "entry-error", source: "evaluation", directory: "manifest", schema: entryErrorSchema },
  { name: "environment", source: "environment", directory: "manifest", schema: environmentStructureSchema },
  { name: "attempt-artifacts", source: "artifacts", directory: "manifest", schema: attemptArtifactsStructureSchema },
  { name: "attempt", source: "attempt", directory: "manifest", schema: attemptStructureSchema },
  { name: "manifest", source: "schema", directory: "manifest", schema: manifestStructureSchema },
  { name: "geometry", source: "geometry", directory: "manifest", schema: geometryStructureSchema },
];

for (const { name, source, schema, directory = "spec" } of schemas) {
  const path = new URL(`../src/${directory}/${name}.schema.json`, import.meta.url);
  const generated = {
    $comment: `Generated by npm run generate:schema from src/${directory}/${source}.ts. Do not edit manually.${name === "spec" ? " Structural validation only; device-proof validate additionally enforces whole-file rules such as unique step names across criteria." : ""}`,
    ...z.toJSONSchema(schema, { target: "draft-2020-12", io: "input", reused: "ref" }),
  };
  const contents = `${JSON.stringify(generated, null, 2)}\n`;

  if (args[0] === "--check") {
    const current = await readFile(path, "utf8").catch((error) => {
      if (error.code === "ENOENT") return undefined;
      throw error;
    });
    if (current !== contents) {
      throw new Error(`Generated ${name} schema is missing or out of date. Run npm run generate:schema.`);
    }
    console.log(`Generated ${name} schema is current.`);
  } else {
    await writeFile(path, contents);
    console.log(`Generated src/${directory}/${name}.schema.json.`);
  }
}
