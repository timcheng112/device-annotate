import { readFile, writeFile } from "node:fs/promises";
import * as z from "zod";
import { buildIdentitySchema } from "../dist/spec/build-identity.js";

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  throw new Error("Usage: node scripts/generate-schema.mjs [--check]");
}

const path = new URL("../src/spec/build.schema.json", import.meta.url);
const schema = {
  $comment: "Generated by npm run generate:schema from src/spec/build-identity.ts. Do not edit manually.",
  ...z.toJSONSchema(buildIdentitySchema, { target: "draft-2020-12", io: "input" }),
};
const contents = `${JSON.stringify(schema, null, 2)}\n`;

if (args[0] === "--check") {
  const current = await readFile(path, "utf8").catch((error) => {
    if (error.code === "ENOENT") return undefined;
    throw error;
  });
  if (current !== contents) {
    throw new Error("Generated build schema is missing or out of date. Run npm run generate:schema.");
  }
  console.log("Generated build schema is current.");
} else {
  await writeFile(path, contents);
  console.log("Generated src/spec/build.schema.json.");
}
