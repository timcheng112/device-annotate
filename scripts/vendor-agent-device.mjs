const source = (path) => execFileSync('git', ['-C', upstream, 'show', `${revision}:${path}`], { encoding: 'utf8' });
const section = (text, start, end) => {
  const from = text.indexOf(start), to = end === undefined ? text.length : text.indexOf(end, from + start.length);
  if (from < 0 || to < 0) throw new Error(`Upstream extraction boundary changed: ${start}`);
  return text.slice(from, to).trim() + '\n';
};
const noImports = (text) => text.replace(/^import [\s\S]*? from ['"][^'"]+['"];\n/gm, '');
