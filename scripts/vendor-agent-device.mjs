async function emit(path, body, original, upstreamPath) {
  const header = `// Generated by scripts/vendor-agent-device.mjs. Do not edit.\n// agent-device v0.21.27, MIT, source ${commit}\n// ${upstreamPath}\n`;
  const content = path.endsWith('LICENSE') ? body : header + body;
  const target = resolve(root, path);
  records.push({ path, source: upstreamPath, sourceSha256: createHash('sha256').update(original).digest('hex'), sha256: createHash('sha256').update(content).digest('hex') });
  if (write) { await mkdir(dirname(target), { recursive: true }); await writeFile(target, content); }
  else if (await readFile(target, 'utf8').catch(() => '') !== content) throw new Error(`Vendor differs: ${path} against ${revision}:${upstreamPath}`);
}
