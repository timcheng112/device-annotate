import { mkdir, readFile, writeFile } from "node:fs/promises";

// Geometry-only review fixture. Production crop/layout work remains in M2/M3.
const names = ["top-left", "top-right", "center", "partial-left", "partial-bottom"];
const fixtures = {};
for (const platform of ["ios", "android"]) {
  const base = new URL(`../test/fixtures/capture-spike/${platform}/`, import.meta.url);
  const snapshot = JSON.parse(await readFile(new URL("capture.snapshot.json", base), "utf8"));
  const png = await readFile(new URL("capture.raw.png", base));
  const width = png.readUInt32BE(16);
  const height = png.readUInt32BE(20);
  const sx = width / snapshot.viewport.width;
  const sy = height / snapshot.viewport.height;
  const targets = Object.fromEntries(names.map((name) => {
    const matches = snapshot.nodes.filter((node) => node.label === name && node.rect);
    if (matches.length !== 1) throw new Error(`Expected one ${platform} fixture target: ${name}`);
    const { rect, identifier } = matches[0];
    return [name, { selector: `id=${JSON.stringify(identifier)}`, x: rect.x * sx, y: rect.y * sy, width: rect.width * sx, height: rect.height * sy }];
  }));
  // Embed neutral images so cmux's file-page access boundary can display them.
  fixtures[platform] = { width, height, targets, image: `data:image/png;base64,${png.toString("base64")}` };
}
const directory = new URL("../docs/prototypes/crop-contract/", import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL("fixtures.js", directory), `// Generated by node scripts/preview-crop.mjs. Do not edit manually.\nconst fixtures = ${JSON.stringify(fixtures, null, 2)};\n`);
console.log("Generated neutral crop-preview geometry from M0 fixtures.");
